<?php
$resources = [
    'Member' => 'members',
    'Account' => 'accounts',
    'Loan' => 'loans',
    'Transaction' => 'transactions',
    'Accounting' => 'accounting',
    'Expense' => 'expenses',
    'Report' => 'reports',
    'User' => 'users',
    'Sms' => 'sms',
    'Email' => 'emails',
    'Document' => 'documents',
    'Setting' => 'settings',
    'Help' => 'help',
];

foreach ($resources as $model => $folder) {
    $controllerName = $model . 'Controller';
    $controllerPath = __DIR__ . '/app/Http/Controllers/' . $controllerName . '.php';
    
    // Create controller content
    $content = "<?php\n\nnamespace App\Http\Controllers;\n\nuse Illuminate\Http\Request;\n\nclass {$controllerName} extends Controller\n{\n";
    $content .= "    public function index() { return view('{$folder}.index'); }\n";
    $content .= "    public function create() { return view('{$folder}.create'); }\n";
    $content .= "    public function store(Request \$request) { return redirect()->route('{$folder}.index')->with('success', 'Created successfully'); }\n";
    $content .= "    public function show(\$id) { return view('{$folder}.show', compact('id')); }\n";
    $content .= "    public function edit(\$id) { return view('{$folder}.edit', compact('id')); }\n";
    $content .= "    public function update(Request \$request, \$id) { return redirect()->route('{$folder}.index')->with('success', 'Updated successfully'); }\n";
    $content .= "    public function destroy(\$id) { return redirect()->route('{$folder}.index')->with('success', 'Deleted successfully'); }\n";
    $content .= "}\n";
    
    file_put_contents($controllerPath, $content);
    
    // Create view directories
    $viewDir = __DIR__ . '/resources/views/' . $folder;
    if (!is_dir($viewDir)) mkdir($viewDir, 0777, true);
    
    // Create basic views
    $views = ['index', 'create', 'show', 'edit'];
    foreach ($views as $view) {
        $viewPath = $viewDir . '/' . $view . '.blade.php';
        if (!file_exists($viewPath) || filesize($viewPath) < 500) { 
            $title = ucfirst($folder) . ' - ' . ucfirst($view);
            $viewContent = "@extends('layouts.app')\n@section('title', '{$title}')\n@section('content')\n";
            $viewContent .= "<div class=\"p-8 bg-white rounded-2xl shadow-sm border border-slate-100\">\n";
            $viewContent .= "    <h1 class=\"text-2xl font-bold mb-4\">{$title}</h1>\n";
            $viewContent .= "    <p class=\"text-slate-500\">This is the autogenerated Blade template for {$title}. The UI logic from React will be inserted here.</p>\n";
            if ($view === 'index') {
                $viewContent .= "    <a href=\"{{ route('{$folder}.create') }}\" class=\"inline-block mt-4 px-4 py-2 bg-sacco text-white rounded\">+ Create New</a>\n";
            } else {
                $viewContent .= "    <a href=\"{{ route('{$folder}.index') }}\" class=\"inline-block mt-4 px-4 py-2 bg-slate-100 text-slate-600 rounded\">Back to List</a>\n";
            }
            $viewContent .= "</div>\n@endsection\n";
            file_put_contents($viewPath, $viewContent);
        }
    }
}
echo "Scaffolded all controllers and views.\n";
